public class IncrementDecrementOperations{

    public static void main(String args[]){
        int a = 10;
        System.out.println("Intial value of a is : "+ a);
        a++;
        System.out.println("After postIncrement value of a is : " + a);
        int b = 5;
        System.out.println("Intial value of b is : "+ b);
        b--;
        System.out.println("After postIncrement value of b is : " + b);
        
    }
}