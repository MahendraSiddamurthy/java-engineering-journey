public class RelationalOperations{

    public static void main(String args[]){

        int a = 10;
        int b =20;

        System.out.println("Greater or not : " + (a >= b));
        System.out.println("Lesser or not : " + (a < b));
        System.out.println("Equal or not : " + (a == b));
        System.out.println("Greater or equal : " + (a >= b));
        System.out.println("Lesser or equal : " + (a <= b));
        System.out.println("Equal or notEqual : " + (a != b));

    }
}